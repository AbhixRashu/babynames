const seen = new Set();

function add(origin, gender, name, meaning, style, extra) {
  const key = `${origin.toLowerCase()}|${name.toLowerCase()}|${gender}`;
  if (seen.has(key)) {
    console.warn(`  duplicate skipped: ${name} (${origin}/${gender})`);
    return;
  }
  if (!name || name.length < 2) {
    console.warn(`  invalid name skipped: ${name}`);
    return;
  }
  seen.add(key);
  return { name, gender, origin, meaning, style, ...extra };
}

function buildOrigin(origin, rows, handler) {
  const out = [];
  for (const [name, gender, meaning, style, extra] of rows) {
    const entry = add(origin, gender, name, meaning, style, handler ? handler(extra, name) : {});
    if (entry) out.push(entry);
  }
  return out;
}

function hinduExtra(override, name) {
  return { rashi: override || rashiFromName(name) };
}
function muslimExtra(category, _name) {
  if (!category) throw new Error('Muslim name missing category');
  if (!MUSLIM_CATEGORIES.includes(category)) throw new Error(`Unknown Muslim category: ${category}`);
  return { category };
}

